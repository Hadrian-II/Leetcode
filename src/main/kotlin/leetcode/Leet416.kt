class Solution416 {
    lateinit var nums: IntArray
    lateinit var overflow: IntArray
    val memo = mutableMapOf<Pair<Int, Int>, Boolean>()

    fun canPartition(nums: IntArray): Boolean {
        this.nums = nums

        var sum = 0
        overflow = IntArray(nums.size)
        for (i in nums.lastIndex downTo 0) {
            sum += nums[i]
            overflow[i] = sum
        }
        if (sum % 2 == 1) {
            return false
        }
        return partition(0, 0)
    }

    private fun partition(i: Int, balance: Int): Boolean {
        return memo.getOrPut(Pair(i, balance)) {
            if (i > nums.lastIndex) {
                balance == 0
            } else if (balance > overflow[i] || -balance > overflow[i]) {
                false
            } else {
                if (balance > 0) {
                    partition(i + 1, balance - nums[i]) || partition(i + 1, balance + nums[i])
                } else {
                    partition(i + 1, balance + nums[i]) || partition(i + 1, balance - nums[i])
                }
            }
        }
    }
}